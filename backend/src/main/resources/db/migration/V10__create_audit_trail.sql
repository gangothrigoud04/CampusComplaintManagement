CREATE TABLE audit_trail (
    id BIGINT NOT NULL AUTO_INCREMENT,
    event_key VARCHAR(36) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    actor_name VARCHAR(160) NOT NULL,
    actor_role VARCHAR(30) NOT NULL,
    action_type VARCHAR(60) NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id VARCHAR(80),
    entity_reference VARCHAR(160),
    complaint_id BIGINT,
    complaint_reference VARCHAR(40),
    description VARCHAR(500) NOT NULL,
    before_state TEXT,
    after_state TEXT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_audit_trail_event_key UNIQUE (event_key),
    INDEX idx_audit_trail_created (created_at, id),
    INDEX idx_audit_trail_actor (actor_user_id, created_at),
    INDEX idx_audit_trail_action (action_type, created_at),
    INDEX idx_audit_trail_role (actor_role, created_at),
    INDEX idx_audit_trail_complaint (complaint_id, created_at)
) ENGINE=InnoDB;
